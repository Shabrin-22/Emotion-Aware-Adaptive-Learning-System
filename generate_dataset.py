def export_dataset(target_dir="data"):
    os.makedirs(target_dir, exist_ok=True)
    csv_path = os.path.join(target_dir, "cognitive_states_dataset.csv")

    rows = []
    for state, samples in CORE_SAMPLES.items():
        for s in samples:
            rows.append((s, state))

    with open(csv_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "state"])
        for text, state in rows:
            writer.writerow([text, state])

    counts = Counter(state for _, state in rows)
    print(f"Dataset exported to {csv_path} with {len(rows)} samples.")
    print("Class distribution:")
    for state, cnt in counts.items():
        print(f"  {state}: {cnt}")
    return csv_path

if __name__ == "__main__":
    export_dataset()
